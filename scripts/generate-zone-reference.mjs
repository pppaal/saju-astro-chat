#!/usr/bin/env node
/**
 * Zone reference point generator (dev only — rerun after a tzdata update).
 *
 * Writes src/lib/saju/zoneReference.generated.ts: for every IANA zone, the
 * latitude/longitude of its principal location, read from the tzdata tables.
 *   1. zone1970.tab — one row per zone since 1970 (the primary source, OD-2).
 *   2. zone.tab     — adds zones that zone1970.tab folds into another zone
 *                     (e.g. Europe/Amsterdam keeps its own coordinates).
 *   3. tzdata.zi    — `L target alias` link lines: an alias gets its target's
 *                     point (Asia/Calcutta → Asia/Kolkata).
 * Etc/* and other fixed-offset zones are not listed: zoneReferenceLongitude()
 * uses offset × 15 for them.
 *
 * Usage:  node scripts/generate-zone-reference.mjs [TZDIR]   (default /usr/share/zoneinfo)
 * Then run prettier on the output and review the diff.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const TZDIR = process.argv[2] || process.env.TZDIR || '/usr/share/zoneinfo'
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src/lib/saju/zoneReference.generated.ts'
)

const read = (name) => readFileSync(join(TZDIR, name), 'utf8')

/** ISO 6709 sign-degrees-minutes[-seconds] → decimal degrees. */
function parseIso6709(coord) {
  const m = /^([+-]\d{4,6})([+-]\d{5,7})$/.exec(coord)
  if (!m) throw new Error(`bad coordinate ${coord}`)
  const part = (s, degDigits) => {
    const sign = s[0] === '-' ? -1 : 1
    const body = s.slice(1)
    const deg = Number(body.slice(0, degDigits))
    const min = Number(body.slice(degDigits, degDigits + 2))
    const sec = body.length > degDigits + 2 ? Number(body.slice(degDigits + 2)) : 0
    return sign * (deg + min / 60 + sec / 3600)
  }
  return [part(m[1], 2), part(m[2], 3)]
}

function readTab(name) {
  const rows = new Map()
  for (const line of read(name).split('\n')) {
    if (!line || line.startsWith('#')) continue
    const [, coord, zone] = line.split('\t')
    rows.set(zone, parseIso6709(coord))
  }
  return rows
}

const version = (/^# version (\S+)/m.exec(read('tzdata.zi')) || [])[1] || 'unknown'
const points = new Map(readTab('zone1970.tab'))
for (const [zone, p] of readTab('zone.tab')) if (!points.has(zone)) points.set(zone, p)

const rawLinks = new Map()
for (const line of read('tzdata.zi').split('\n')) {
  if (!line.startsWith('L ')) continue
  const [, target, alias] = line.split(' ')
  rawLinks.set(alias, target)
}
const links = new Map()
for (const [alias, target] of rawLinks) {
  if (points.has(alias)) continue
  // Follow chained links to a listed zone; links into Etc/* stay out (offset rule).
  let t = target
  for (let i = 0; i < 5 && !points.has(t) && rawLinks.has(t); i++) t = rawLinks.get(t)
  if (points.has(t)) links.set(alias, t)
}

const r2 = (n) => Math.round(n * 100) / 100
const byName = (a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)
const pointLines = [...points.entries()]
  .sort(byName)
  .map(([z, [lat, lon]]) => `  '${z}': [${r2(lat)}, ${r2(lon)}],`)
const linkLines = [...links.entries()].sort(byName).map(([a, t]) => `  '${a}': '${t}',`)

const out = `// GENERATED by scripts/generate-zone-reference.mjs from tzdata ${version} — do not edit by hand.
//
// IANA zone → [latitude, longitude] of the zone's principal location
// (zone1970.tab, then zone.tab), rounded to 0.01°. zoneReferenceLongitude()
// (src/lib/saju/timezone.ts) reads it when a birth has a timezone but no
// longitude (engine audit OD-2). Etc/* zones are absent on purpose: they use
// offset × 15.

/** Zone → [latitude, longitude] in degrees (east and north positive). */
export const ZONE_REFERENCE_POINTS: Readonly<Record<string, readonly [number, number]>> = {
${pointLines.join('\n')}
}

/** tzdata link (alias) → the listed zone whose point it shares. */
export const ZONE_LINKS: Readonly<Record<string, string>> = {
${linkLines.join('\n')}
}
`
writeFileSync(OUT, out)
console.log(`wrote ${OUT}: ${points.size} zones, ${links.size} links (tzdata ${version})`)
